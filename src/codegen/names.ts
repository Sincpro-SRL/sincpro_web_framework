import type { Metamodel } from "@sincpro/web-framework/codegen/metamodel";

/**
 * How the generator names what the server names: a TypeScript identifier for a class, a method
 * for an operation, a value for an entity, the key the workspace refers to an entity by.
 *
 * Context: every name here is derived, the same way every time, from what the contract already
 * says — never chosen — so regenerating never renames by itself. Two things that come out with
 * one name are refused by whoever writes them, naming both (`claimed`): a silent rename would
 * break whoever imported the first.
 */

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * What a generated file imports, built in parts. The build rewrites this package's own
 * specifiers to relative paths (`tsc-alias`), and it reads `from "…"` inside a string too: written
 * whole, the generated files came out importing `"../index.js"` and `"./domain.js"`.
 */
export const FRAMEWORK = ["@sincpro", "web-framework"].join("/");
export const FRAMEWORK_CORE = [FRAMEWORK, "core"].join("/");
export const DOMAIN_MODULE = [".", "domain"].join("/");

/** A name of the server's as a TypeScript identifier: `shop__orders__Line` stays, `-` is `_`. */
export function identifierOf(name: string): string {
  const cleaned = name.replace(/[^A-Za-z0-9_$]/g, "_");
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned;
}

/** A property key as TypeScript writes it: bare when it can be, quoted otherwise. */
export function keyOf(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

export function sorted<V>(record: Readonly<Record<string, V>>): [string, V][] {
  return Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** `{ Issue: "issue_id" }`: a record of texts as TypeScript writes it, keys sorted. */
export function recordLiteral(record: Readonly<Record<string, string>>): string {
  const entries = sorted(record).map(
    ([key, value]) => `${keyOf(key)}: ${JSON.stringify(value)}`,
  );
  return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`;
}

/** The bounded context's own name: `bounded_context`, or `context` in a 3.32 contract. */
export function contextOf(metamodel: Metamodel): string {
  const name = metamodel.bounded_context ?? metamodel.context;
  if (name === undefined) throw new Error("the contract names no bounded context");
  return name;
}

/** What a client names the context by: its `alias`, else its own name. */
export function aliasOf(metamodel: Metamodel): string {
  return metamodel.alias ?? contextOf(metamodel);
}

/** A model the contract names is an entity when it has an identity; else a value it holds. */
export function isEntity(metamodel: Metamodel, model: string): boolean {
  return metamodel.models[model]?.["x-sincpro"]?.identity !== undefined;
}

/** An operation's name in its context: its identity without `<bounded_context>.`. */
export function localOf(metamodel: Metamodel, identity: string): string {
  const prefix = `${contextOf(metamodel)}.`;
  return identifierOf(identity.startsWith(prefix) ? identity.slice(prefix.length) : identity);
}

/** The method an operation is called by: `CommandSendIssue` → `sendIssue`. */
export function methodOf(local: string): string {
  const bare = local.replace(/^(Command|Query)(?=[A-Z])/, "");
  return `${bare.charAt(0).toLowerCase()}${bare.slice(1)}`;
}

/** `Issue` → `issues`, `ProjectEvent` → `projectEvents`, `Policy` → `policies`. */
export function pluralOf(name: string): string {
  const value = `${name.charAt(0).toLowerCase()}${name.slice(1)}`;
  if (/[^aeiou]y$/.test(value)) return `${value.slice(0, -1)}ies`;
  if (/(s|x|z|ch|sh)$/.test(value)) return `${value}es`;
  return `${value}s`;
}

/** A JSDoc block, or nothing: the paragraphs given, each one kept. */
export function docOf(lines: readonly (string | null | undefined)[], pad: string): string {
  const text = lines
    .filter((one): one is string => typeof one === "string" && one.trim() !== "")
    .join("\n\n")
    .replace(/\*\//g, "*\\/")
    .trim();
  if (text === "") return "";
  const parts = text.split("\n");
  if (parts.length === 1) return `${pad}/** ${parts[0]} */\n`;
  const body = parts.map((one) => `${pad} *${one === "" ? "" : ` ${one}`}`).join("\n");
  return `${pad}/**\n${body}\n${pad} */\n`;
}

/** The first lines of every generated file: what it is, where it came from, not to edit it. */
export function headerOf(what: string, metamodel: Metamodel): string {
  const alias = aliasOf(metamodel);
  const own = contextOf(metamodel);
  return [
    `// ${what} of «${alias}»${alias === own ? "" : ` (${own})`}, generated by @sincpro/web-framework.`,
    `// Version ${metamodel.version}.`,
    `// Do not edit: regenerate it (\`sincpro-web generate\`).`,
  ].join("\n");
}

/** What a deprecated operation says: since when it goes and what replaces it. */
export function deprecationOf(
  metamodel: Metamodel,
  operation: { deprecated?: boolean; sunset?: string | null; replacement?: string | null },
): string | undefined {
  if (operation.deprecated !== true) return undefined;
  const sunset = operation.sunset ? ` It stops being served on ${operation.sunset}.` : "";
  const replacement = operation.replacement
    ? ` Use \`${localOf(metamodel, operation.replacement)}\`.`
    : "";
  return `@deprecated${sunset}${replacement}`;
}

/** Refuses a second thing under a name already given, naming both. */
export function claimed(): (name: string, by: string) => void {
  const named = new Map<string, string>();
  return (name, by) => {
    const before = named.get(name);
    if (before !== undefined)
      throw new Error(`${by} and ${before} are both "${name}" in TypeScript: rename one`);
    named.set(name, by);
  };
}
